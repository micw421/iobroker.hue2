import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { definitions } from 'zigbee-herdsman-converters/devices/philips';

const mappings = new Map();

function add(modelId, imageModel) {
    if (typeof modelId !== 'string' || modelId.length === 0 || typeof imageModel !== 'string' || imageModel.length === 0) return;
    const existing = mappings.get(modelId);
    if (existing && existing !== imageModel) {
        throw new Error(`Conflicting Philips mapping for ${modelId}: ${existing} vs. ${imageModel}`);
    }
    mappings.set(modelId, imageModel);
}

for (const definition of definitions) {
    for (const modelId of definition.zigbeeModel ?? []) add(modelId, definition.model);
    for (const fingerprint of definition.fingerprint ?? []) add(fingerprint.modelID, definition.model);

    for (const whiteLabel of definition.whiteLabel ?? []) {
        const imageModel = whiteLabel.model ?? definition.model;
        for (const fingerprint of whiteLabel.fingerprint ?? []) add(fingerprint.modelID, imageModel);
    }
}

const sorted = Object.fromEntries([...mappings.entries()].sort(([a], [b]) => a.localeCompare(b)));
const output = `// This file is generated by scripts/update-philips-device-images.mjs.
// Source: zigbee-herdsman-converters Philips device definitions.
// Do not edit manually.

export const PHILIPS_DEVICE_IMAGE_MODELS: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 4)};
`;

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, '../src/lib/philips-device-images.generated.ts');
await writeFile(target, output, 'utf8');
console.log(`Wrote ${mappings.size} Philips model mappings to ${target}`);
